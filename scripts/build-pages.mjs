#!/usr/bin/env node
// Builds the hosted web demo into dist/: the page, the example knowledge base and an
// in-browser stand-in for the AI helpers. No server and no keys are involved.
//   node scripts/build-pages.mjs [--kb kb/example.json] [--out dist]
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadKb, STOP, stems, mockMatch } from "../server.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const arg = (name, def) => { const i = process.argv.indexOf(name); return i > 0 ? process.argv[i + 1] : def; };
const kbFile = path.resolve(arg("--kb", path.join(ROOT, "kb", "example.json")));
const out = path.resolve(arg("--out", path.join(ROOT, "dist")));

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(ROOT, "public"), out, { recursive: true });
const kb = loadKb(kbFile);
fs.writeFileSync(path.join(out, "kb.json"), JSON.stringify({ ...kb, ai: { match: true, draft: true, mock: true } }));
fs.writeFileSync(path.join(out, "static.js"), `"use strict";
// Generated by scripts/build-pages.mjs: the pretend AI of the web demo, run in the browser.
(() => {
const STOP = new Set(${JSON.stringify([...STOP])});
const stems = ${stems.toString()};
${mockMatch.toString()}
window.CALL_CUE_STATIC = {
  kbUrl: "kb.json",
  api(p, body, kb) {
    if (p === "/api/match") return mockMatch(kb, body.latest || "");
    if (p === "/api/draft") return { text: "(mock draft) " + (kb.fallback || "Let me check that and confirm in writing.") };
    if (p === "/api/summary") return { text: "(mock summary)\\nAsked: " + String(body.transcript || "").split("\\n").filter(Boolean).length + " lines\\nAnswered: -\\nFollow-ups: -" };
    throw new Error("not available in the web demo");
  },
};
})();
`);
const idx = path.join(out, "index.html");
fs.writeFileSync(idx, fs.readFileSync(idx, "utf8").replace('<script src="app.js"></script>', '<script src="static.js"></script>\n<script src="app.js"></script>'));
console.log("web demo built in " + out);
